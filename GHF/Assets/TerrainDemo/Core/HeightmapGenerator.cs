// ── 实现原理与思路(自然段) ──────────────────────────────────────────────────
//
// 目的。这一步把"噪声的数学定义"落成"一张具体的、可比较的数据表"。演讲稿的管线
// 叙述是"分层噪声建立结构与细节,种子控制可复现性,最后转成三维网格",本类承载
// 前两步的合流点:输入只有参数,输出只有数据,中间不碰任何 Unity 对象。正因为
// 输入输出都是纯数据,"同种子同参数 ⇒ 位级相同的高度图"才能被测试直接验证——
// 这是可控性标准从理论变成可测事实的地方。
//
// 实现原理。外层是一次 [Resolution, Resolution] 的行主序双循环:先由边长与分辨率
// 算出格距 cell,把格点下标换算成世界坐标 (x, z),交给 FractalNoise2D.Sample 采样,
// 得到 [0,1] 的归一化高度,再做一次 h^HeightExponent 的幂次重映射写入数组。幂次
// 重映射是低成本的造型手段:指数大于 1 时谷底被压平、峰顶被拉高,山脊线立刻清晰
// (服务结构保真度);等于 1 则完全不改变形状。整个函数的确定性由三层保证——
// 随机性只来自种子构造的噪声实例、循环次序固定、运算全部是逐位确定的浮点算术。
//
// 思路。噪声实例应当在循环外构造一次,循环内只做采样,这是性能与结构的自然边界;
// 数组按 [z, x] 索引虽与直觉的 [x, y] 相反,但与后续网格构建"第 z 行第 x 列"的顶点
// 排布一致,两个模块沿用同一约定可以少一次转置。分辨率很大时这一步是内存与耗时
// 的大头(257² 个 float 约 260KB,毫秒级),将来若做性能优化,这里是最先被拆给
// Job System 的候选,接口保持纯函数也为那种改造预留了空间。
