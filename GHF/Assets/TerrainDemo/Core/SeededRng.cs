// ── 实现原理与思路(自然段) ──────────────────────────────────────────────────
//
// 目的。地形生成之所以能做到"同一种子必然复现同一座山",前提是所有看似随机的
// 数据——置换表、随机偏移——都派生自同一个可控源头。本类就是这个唯一源头:它把
// 演讲稿中"可控性"这一评价标准落实为代码层面的约束,即除了这里,任何代码都不得
// 使用随机数(包括 UnityEngine.Random 和 System.Random),否则确定性链条就会断裂。
//
// 实现原理。推荐采用 splitmix64:每输出一次,先把 64 位状态累加一个黄金比例常数
// 0x9E3779B97F4A7C15,再把状态值做三轮"异或移位 + 乘大奇数"的混合(依次乘
// 0xBF58476D1CE4E5B9、0x94D049BB133111EB),得到均匀分布的 64 位输出。它与演讲稿
// 引用的 Mersenne Twister(Matsumoto & Nishimura, 1998)共享同一理论性质——种子
// 决定初始状态,之后是纯确定性递推——但状态只有 8 字节,一行就能算完,对本项目的
// 采样量绰绰有余。Next01 取输出的高 24 位除以 2^24,一方面 float 的尾数恰好 24 位,
// 结果落在 [0,1) 内且无舍入;另一方面保证永远取不到 1。
//
// 思路。构造函数只做一件事:把 int 种子(可正可负可为零)转换并混入 64 位状态,
// 常见做法是先强转 ulong 再与固定常数做异或、加法扰动,确保相邻种子给出毫不相似的
// 序列;NextUInt 完成一次状态推进并输出;Next01 基于 NextUInt 做区间映射。三者都不
// 读时间、不读环境,构造后只由调用方驱动,这样才能通过"同种子逐项一致"的测试。
