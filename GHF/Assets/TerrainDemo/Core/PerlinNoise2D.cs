// ── 实现原理与思路(自然段) ──────────────────────────────────────────────────
//
// 目的。这是整条管线最底层的"连续随机场":fBm 的每一个 octave 都是对它的采样。
// 选型依据来自 Lagae et al. (2010) 的噪声综述——梯度噪声以极低的计算成本换来了
// 良好的各向同性和频谱可控性,在速度与质量的取舍上最适合本项目;而 Unity 自带的
// Mathf.PerlinNoise 无法播种,种子进不了噪声内部,可控性不达标,所以需要自己实现。
//
// 实现原理。经典 Perlin 把平面切成单位网格,每个格点藏着一个固定长度的梯度向量;
// 采样时先定位所在格子,算出分数坐标,用五次多项式 fade(t)=6t^5−15t^4+10t^3 做缓动
// (它保证一阶导数在 0 和 1 处都为零,噪声场处处连续光滑),再用置换表把四个角点
// 的坐标映射成梯度索引,对"角点梯度 · 角点到采样点的偏移"做点积,最后双线性插值。
// 置换表是 0..255 的随机排列,下标运算 perm[perm[X] + Y] 双重混淆,让相邻格点的
// 梯度选择互不相关。整数格点返回 0 是这条流水线的自然结果(偏移向量为零,点积为零),
// 256 周期则来自坐标对 256 取模,这两个"免费性质"都被测试用来验证实现正确性。
//
// 思路。构造函数里用 SeededRng 做 Fisher-Yates 洗牌生成置换表——种子通过它进入
// 噪声场,这是"种子可复现"能一路传导到最终高度图的关键一环;负坐标必须用 floor
// 取整再按位与 255(对负数用取余会出错),这是测试专门覆盖的易错点。梯度表可以
// 预生成 8 或 12 个单位向量,也可以用位运算从置换值现场构造,两种做法都能满足契约。
// Noise 本身应当是无状态的纯函数,不修改任何成员,这样任意多次重放都安全。
